int	main(int argc, char **argv)
{
	t_config	config;

	if (!parser(argc, argv, &config))
		return (1);
	if (!init_config(&config))
		printf("The malloc has failed");
	if (!start_simulation(&config))
		printf("The simulation failed");
}
